"""Generated inventory of every agent, skill, rule, role, model adapter and tool in this repository.

``python -m agy_studio inventory`` prints the Markdown; ``--write`` refreshes ``docs/AGENTS_AND_SKILLS.md``. A unit
test asserts the committed file equals the generated text, so the page cannot drift from ``roles.py``,
``registry.yaml``, ``.agents/`` and the MCP server.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import yaml

from .agents.roles import ROLES, RoleSpec

DOC_REL_PATH = Path("docs") / "AGENTS_AND_SKILLS.md"

_DEPARTMENT_ORDER = ("cross-cutting", "story", "art", "direction", "audio", "production", "post")
_KIND_LABELS = {
    "video_av": "video + native speech",
    "music": "music score stems",
    "sfx": "foley / hard effects",
    "image": "images (keyframes, reference sheets)",
    "transcribe": "speech transcription (QA)",
    "speaker_similarity": "voice similarity vs. anchor (QA)",
    "vision_judge": "visual continuity / QA judge",
    "llm": "role-agent reasoning",
}


def _frontmatter(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    try:
        data = yaml.safe_load(text[3:end]) or {}
    except yaml.YAMLError:
        return {}
    return {str(k): " ".join(str(v).split()) for k, v in data.items()} if isinstance(data, dict) else {}


def _first_heading(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#"):
            return line.lstrip("#").strip()
    return path.stem


def _shorten(text: str, limit: int = 160) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _mcp_tools(repo_root: Path) -> list[str]:
    src = repo_root / "resolve_mcp_server.py"
    if not src.is_file():
        return []
    text = src.read_text(encoding="utf-8")
    return re.findall(r"@mcp\.tool\([^)]*\)\s*\n\s*(?:async\s+)?def\s+([A-Za-z_][A-Za-z0-9_]*)", text)


def _registry_models(repo_root: Path) -> list[dict[str, Any]]:
    data = yaml.safe_load((repo_root / "agy_studio" / "registry.yaml").read_text(encoding="utf-8")) or {}
    return [m for m in data.get("models", []) if isinstance(m, dict)]


def _role_row(spec: RoleSpec) -> str:
    impl = f"`{spec.implementation}`" if spec.implementation else "prompt only"
    gate = spec.gate or "—"
    loop = " · direction loop" if spec.loop else ""
    return f"| `{spec.name}` | {spec.title} | {spec.scope} | {gate} | `{spec.output_kind}` | {impl}{loop} |"


def render_inventory(repo_root: Path) -> str:
    repo_root = Path(repo_root)
    agents_dir = repo_root / ".agents"
    out: list[str] = [
        "# AGY Studio — Agents, Skills & Tools Inventory",
        "",
        "> Generated by `python -m agy_studio inventory --write` from `agy_studio/agents/roles.py`, "
        "`agy_studio/registry.yaml`, `.agents/` and `resolve_mcp_server.py`. Do not edit by hand — "
        "`tests/agy/test_agy_inventory.py` fails when this file is stale.",
        "",
        "## 1. Antigravity customizations (`.agents/`)",
        "",
        "| Kind | Name | Purpose |",
        "|---|---|---|",
    ]
    for f in sorted((agents_dir / "agents").glob("*.md")):
        fm = _frontmatter(f)
        out.append(f"| Agent | `{fm.get('name', f.stem)}` | {_shorten(fm.get('description', _first_heading(f)))} |")
    for f in sorted((agents_dir / "skills").glob("*/SKILL.md")):
        fm = _frontmatter(f)
        out.append(f"| Skill | `{fm.get('name', f.parent.name)}` | {_shorten(fm.get('description', _first_heading(f)))} |")
    for f in sorted((agents_dir / "rules").glob("*.md")):
        out.append(f"| Rule | `{f.stem}` | {_shorten(_first_heading(f))} |")
    if (agents_dir / "AGENTS.md").is_file():
        out.append(f"| Guide | `AGENTS.md` | {_shorten(_first_heading(agents_dir / 'AGENTS.md'))} |")
    if (repo_root / "GEMINI.md").is_file():
        out.append(f"| Rules (Gemini) | `GEMINI.md` | {_shorten(_first_heading(repo_root / 'GEMINI.md'))} |")

    out += [
        "",
        f"## 2. Engine role agents (`agy_studio/agents/roles.py`) — {len(ROLES)} roles",
        "",
        "Every role has a prompt in `agy_studio/agents/prompts/<name>.md`; roles with an *implementation* are backed "
        "by deterministic Python behind the prompt. `direction loop` roles run multi-round at G3.",
        "",
    ]
    for dept in _DEPARTMENT_ORDER:
        rows = [s for s in ROLES.values() if s.department == dept]
        if not rows:
            continue
        out += [f"### {dept.replace('-', ' ').title()}", "",
                "| Role | Title | Scope | Gate | Output | Implementation |", "|---|---|---|---|---|---|"]
        out += [_role_row(s) for s in rows]
        out.append("")
    other = [s for s in ROLES.values() if s.department not in _DEPARTMENT_ORDER]
    if other:
        out += ["### Other", "", "| Role | Title | Scope | Gate | Output | Implementation |", "|---|---|---|---|---|---|"]
        out += [_role_row(s) for s in other]
        out.append("")

    out += [
        "## 3. Model adapters (`agy_studio/registry.yaml` → `agy_studio/adapters/`)",
        "",
        "All adapters authenticate through `agy_studio/adapters/auth.py` (fail-fast gcloud pre-flight; no offline "
        "or fake production mode exists).",
        "",
        "| Model id | Kind | Provider model | Fallbacks | Adapter |",
        "|---|---|---|---|---|",
    ]
    for m in _registry_models(repo_root):
        if not m.get("enabled", True):
            continue
        fallbacks = ", ".join(f"`{x}`" for x in m.get("provider_fallbacks") or []) or "—"
        kind = m.get("kind", "?")
        out.append(f"| `{m.get('id')}` | {_KIND_LABELS.get(kind, kind)} | `{m.get('provider_model', '?')}` | "
                   f"{fallbacks} | `{m.get('adapter', '?')}` |")

    tools = _mcp_tools(repo_root)
    out += [
        "",
        "## 4. Tool servers & subsystems",
        "",
        f"### DaVinci Resolve MCP server (`resolve_mcp_server.py`) — {len(tools)} tools",
        "",
        "An agent convenience for inspecting/editing the NLE. **Not** the delivery path: the engine pushes cuts itself "
        "through `FailoverTransport` (`LuaMenuTransport` → `ScriptApiTransport`).",
        "",
        ", ".join(f"`{t}`" for t in tools) or "(none found)",
        "",
        "### Engine subsystems",
        "",
        "| Subsystem | Module | What it does |",
        "|---|---|---|",
        "| Orchestrator (gates G0–G7, director / hybrid / autopilot) | `agy_studio/orchestrator.py` | Scene state machine, gate packets, self-healing `auth` blocker, autopilot self-approval |",
        "| Live dashboard | `agy_studio/dashboard.py`, `agy_studio/dashboard_web.py` | `DASHBOARD.md` after every step + local web page: status, time, tokens/cost, ETA, risks, bibles, outputs, QA failures with prompts |",
        "| Time accounting | `agy_studio/trace.py` | `trace`: per-role LLM durations, gates, questions, provider jobs, silent gaps |",
        "| Credential pre-flight | `agy_studio/adapters/auth.py` | gcloud discovery, token minting with real error text, `AuthError` fail-fast |",
        "| Resolve delivery | `agy_studio/resolve_bridge.py` | Additive BridgeOps → Lua menu click → scripting API fallback; manual one-click route if both fail |",
        "| 3D set (opt-in only) | `agy_studio/set3d/` | Grey-box designer, browser FPV viewer, Blender exporter + `set3d open-blender` launcher, style pass |",
        "| Two-tier draft→finalize & critics | `agy_studio/harness_v5.py` | `DraftFinalizeController` (360p→4K), `VisualContinuityCritic` (3×3 sheet), `SceneSlate`, `StateTokenGuard`, `TimelineGitRepo` |",
        "| Pre-flight lint (18 rules) | `agy_studio/linter.py` | Refuses to dispatch clips that would fail or waste money |",
        "| Voice spec lock (G4, no audio) | `agy_studio/voice_audition.py` | Physical voice description that feeds the video model's prompt; anchor from first approved take |",
        "| QA critic | `agy_studio/qa_critic.py` | Transcript match, speaker similarity, RAI/music/subtitle hard rejects, take ranking |",
        "| Editor / assembly | `agy_studio/editor.py` | Scene cut, OTIO/FCPXML, final `.mp4` |",
        "",
        "### Legacy v1 scripts (repo root)",
        "",
        "`vertex_veo_director.py` (Omni/Veo clients used by the adapters), `pro_audio_director.py` (Lyria / SFX), "
        "`casting_agent.py`, `dialogue_agent.py`, `production_bible.py`, `production_ledger.py`, "
        "`new_project_template.py`, `resolve_sync_trigger.py`, `resolve_mcp_server.py`. Minute-one intake: `bootstrap_intake.py` (stdlib only).",
        "",
    ]
    return "\n".join(out)


def write_inventory(repo_root: Path) -> Path:
    path = Path(repo_root) / DOC_REL_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_inventory(repo_root), encoding="utf-8")
    return path
